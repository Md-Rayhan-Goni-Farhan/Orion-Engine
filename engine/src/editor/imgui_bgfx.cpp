// ── Static state ──────────────────────────────────────────────────────────────
static bgfx::VertexLayout   s_layout;
static bgfx::ProgramHandle  s_program     = BGFX_INVALID_HANDLE;
static bgfx::TextureHandle  s_fontTexture = BGFX_INVALID_HANDLE;
static bgfx::UniformHandle  s_texUniform  = BGFX_INVALID_HANDLE;
static uint8_t              s_viewId      = 255;

// ── Init ──────────────────────────────────────────────────────────────────────
bool imguiBgfxInit(int viewId, bgfx::TextureHandle* fontTexture)
{
    s_viewId = (uint8_t)viewId;

    s_layout.begin()
        .add(bgfx::Attrib::Position,  2, bgfx::AttribType::Float)
        .add(bgfx::Attrib::TexCoord0, 2, bgfx::AttribType::Float)
        .add(bgfx::Attrib::Color0,    4, bgfx::AttribType::Uint8, true)
        .end();

    s_texUniform = bgfx::createUniform("s_tex", bgfx::UniformType::Sampler);

    printf("Creating shaders...\n");
    bgfx::ShaderHandle vs = bgfx::createShader(
        bgfx::makeRef(s_vs_dx11, sizeof(s_vs_dx11)));
    printf("VS valid: %d\n", bgfx::isValid(vs));

    bgfx::ShaderHandle fs = bgfx::createShader(
        bgfx::makeRef(s_fs_dx11, sizeof(s_fs_dx11)));
    printf("FS valid: %d\n", bgfx::isValid(fs));

    s_program = bgfx::createProgram(vs, fs, true);
    printf("Program valid: %d\n", bgfx::isValid(s_program));

    if (!bgfx::isValid(s_program))
    {
        printf("Shader program creation FAILED - bytecode mismatch\n");
        return false;
    }

    // Build font atlas texture
    ImGuiIO& io = ImGui::GetIO();
    unsigned char* pixels;
    int width, height;
    io.Fonts->GetTexDataAsRGBA32(&pixels, &width, &height);

    s_fontTexture = bgfx::createTexture2D(
        (uint16_t)width, (uint16_t)height,
        false, 1,
        bgfx::TextureFormat::BGRA8,
        0,
        bgfx::copy(pixels, width * height * 4)
    );

    io.Fonts->SetTexID((ImTextureID)(uintptr_t)s_fontTexture.idx);
    io.Fonts->ClearTexData();

    if (fontTexture)
        *fontTexture = s_fontTexture;

    return true;
}

// ── Shutdown ──────────────────────────────────────────────────────────────────
void imguiBgfxShutdown()
{
    if (bgfx::isValid(s_program))     bgfx::destroy(s_program);
    if (bgfx::isValid(s_fontTexture)) bgfx::destroy(s_fontTexture);
    if (bgfx::isValid(s_texUniform))  bgfx::destroy(s_texUniform);
}

// ── Render ────────────────────────────────────────────────────────────────────
void imguiBgfxRender(ImDrawData* drawData)
{
    if (!drawData || drawData->CmdListsCount == 0)
        return;

    const bgfx::Caps* caps = bgfx::getCaps();
    float ortho[16];
    float x = drawData->DisplayPos.x;
    float y = drawData->DisplayPos.y;
    float w = drawData->DisplaySize.x;
    float h = drawData->DisplaySize.y;
    bx::mtxOrtho(ortho, x, x + w, y + h, y, 0.0f, 1000.0f,
        0.0f, caps->homogeneousDepth);

    bgfx::setViewTransform(s_viewId, nullptr, ortho);
    bgfx::setViewRect(s_viewId, 0, 0, (uint16_t)w, (uint16_t)h);

    for (int i = 0; i < drawData->CmdListsCount; ++i)
    {
        const ImDrawList* drawList = drawData->CmdLists[i];

        uint32_t numVertices = (uint32_t)drawList->VtxBuffer.size();
        uint32_t numIndices  = (uint32_t)drawList->IdxBuffer.size();

        if (!bgfx::getAvailTransientVertexBuffer(numVertices, s_layout) ||
            !bgfx::getAvailTransientIndexBuffer(numIndices))
            break;

        bgfx::TransientVertexBuffer tvb;
        bgfx::TransientIndexBuffer  tib;
        bgfx::allocTransientVertexBuffer(&tvb, numVertices, s_layout);
        bgfx::allocTransientIndexBuffer(&tib, numIndices);

        memcpy(tvb.data, drawList->VtxBuffer.begin(),
            numVertices * sizeof(ImDrawVert));
        memcpy(tib.data, drawList->IdxBuffer.begin(),
            numIndices * sizeof(ImDrawIdx));

        uint32_t offset = 0;
        for (const ImDrawCmd& cmd : drawList->CmdBuffer)
        {
            if (cmd.UserCallback)
            {
                cmd.UserCallback(drawList, &cmd);
            }
            else if (cmd.ElemCount > 0)
            {
                uint64_t state =
                    BGFX_STATE_WRITE_RGB |
                    BGFX_STATE_WRITE_A   |
                    BGFX_STATE_BLEND_FUNC(
                        BGFX_STATE_BLEND_SRC_ALPHA,
                        BGFX_STATE_BLEND_INV_SRC_ALPHA);

                bgfx::TextureHandle th = s_fontTexture;
                if (cmd.GetTexID())
                    th.idx = (uint16_t)(uintptr_t)cmd.GetTexID();

                const uint16_t xx = (uint16_t)bx::max(cmd.ClipRect.x - x, 0.0f);
                const uint16_t yy = (uint16_t)bx::max(cmd.ClipRect.y - y, 0.0f);
                bgfx::setScissor(xx, yy,
                    (uint16_t)bx::min(cmd.ClipRect.z - x, 65535.0f) - xx,
                    (uint16_t)bx::min(cmd.ClipRect.w - y, 65535.0f) - yy);

                bgfx::setState(state);
                bgfx::setTexture(0, s_texUniform, th);
                bgfx::setVertexBuffer(0, &tvb, 0, numVertices);
                bgfx::setIndexBuffer(&tib, offset, cmd.ElemCount);
                bgfx::submit(s_viewId, s_program);
            }
            offset += cmd.ElemCount;
        }
    }
}