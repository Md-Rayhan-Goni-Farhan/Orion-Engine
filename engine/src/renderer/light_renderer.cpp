// ── LightRenderer ────────────────────────────────────────────────────────────

bool LightRenderer::init()
{
    m_layout.begin()
        .add(bgfx::Attrib::Color0,    4, bgfx::AttribType::Uint8, true)
        .add(bgfx::Attrib::Position,  3, bgfx::AttribType::Float)
        .add(bgfx::Attrib::TexCoord0, 2, bgfx::AttribType::Float)
        .end();

    bgfx::ShaderHandle vs = bgfx::createShader(
        bgfx::makeRef(s_vs_light_dx11, sizeof(s_vs_light_dx11)));
    bgfx::ShaderHandle fs = bgfx::createShader(
        bgfx::makeRef(s_fs_light_dx11, sizeof(s_fs_light_dx11)));
    m_program = bgfx::createProgram(vs, fs, true);

    if (!bgfx::isValid(m_program))
    {
        printf("Light shader program creation FAILED\n");
        return false;
    }

    m_colorUniform = bgfx::createUniform("s_tex0", bgfx::UniformType::Sampler);

    printf("Light renderer initialized\n");
    return true;
}

void LightRenderer::shutdown()
{
    if (bgfx::isValid(m_colorUniform)) bgfx::destroy(m_colorUniform);
    if (bgfx::isValid(m_program))      bgfx::destroy(m_program);
}

void LightRenderer::draw(const float* viewMtx, const float* projMtx,
                         const bx::Vec3& position, const bx::Vec3& direction,
                         const float color[3], bool isSelected)
{
    // Softbox dimensions (local space, Z = forward / open face direction)
    const float hw = 0.20f;  // half-width
    const float hh = 0.15f;  // half-height
    const float d  = 0.20f;  // depth (back is at +d along Z, front/open at Z=0)

    // 8 corners: front face (open) at Z=0, back face at Z=+d
    // Front: f0 f1 f2 f3 — Back: b0 b1 b2 b3
    // f0 = (-hw, -hh, 0), f1 = (+hw, -hh, 0), f2 = (+hw, +hh, 0), f3 = (-hw, +hh, 0)
    // b0 = (-hw, -hh, +d), b1 = (+hw, -hh, +d), b2 = (+hw, +hh, +d), b3 = (-hw, +hh, +d)

    float bright = isSelected ? 1.4f : 1.0f;
    uint8_t r = (uint8_t)bx::min(color[0] * bright * 255.0f, 255.0f);
    uint8_t g = (uint8_t)bx::min(color[1] * bright * 255.0f, 255.0f);
    uint8_t b = (uint8_t)bx::min(color[2] * bright * 255.0f, 255.0f);

    struct Vertex { uint8_t cr, cg, cb, ca; float x, y, z; float u, v; };

    Vertex verts[8] = {
        { r,g,b,255, -hw, -hh,  0.0f, 0,0 }, // f0
        { r,g,b,255, +hw, -hh,  0.0f, 0,0 }, // f1
        { r,g,b,255, +hw, +hh,  0.0f, 0,0 }, // f2
        { r,g,b,255, -hw, +hh,  0.0f, 0,0 }, // f3
        { r,g,b,255, -hw, -hh, +d,    0,0 }, // b0
        { r,g,b,255, +hw, -hh, +d,    0,0 }, // b1
        { r,g,b,255, +hw, +hh, +d,    0,0 }, // b2
        { r,g,b,255, -hw, +hh, +d,    0,0 }, // b3
    };

    // 12 lines: 4 front edges, 4 back edges, 4 side edges
    // Front face is NOT drawn (open). Back face and all 4 sides are drawn.
    

    // Build orientation vectors
    bx::Vec3 fwd = bx::normalize(direction);
    bx::Vec3 worldUp = { 0.0f, 1.0f, 0.0f };
    if (bx::abs(bx::dot(fwd, worldUp)) > 0.99f)
        worldUp = { 1.0f, 0.0f, 0.0f };
    bx::Vec3 right = bx::normalize(bx::cross(worldUp, fwd));
    bx::Vec3 up    = bx::cross(fwd, right);

    // Transform vertices into world space on CPU so we don't need u_model in the shader
    struct WorldVertex { uint8_t cr, cg, cb, ca; float x, y, z; float u, v; };
    WorldVertex wverts[8];
    for (int i = 0; i < 8; ++i)
    {
        float lx = verts[i].x, ly = verts[i].y, lz = verts[i].z;
        wverts[i].cr = verts[i].cr; wverts[i].cg = verts[i].cg;
        wverts[i].cb = verts[i].cb; wverts[i].ca = verts[i].ca;
        wverts[i].x = position.x + right.x*lx + up.x*ly + fwd.x*lz;
        wverts[i].y = position.y + right.y*lx + up.y*ly + fwd.y*lz;
        wverts[i].z = position.z + right.z*lx + up.z*ly + fwd.z*lz;
        wverts[i].u = 0.0f; wverts[i].v = 0.0f;
    }

    uint16_t lines[20] = {
        4,5, 5,6, 6,7, 7,4,
        0,4, 1,5, 2,6, 3,7,
        0,2, 1,3,
    };

    bgfx::TransientVertexBuffer tvb;
    bgfx::TransientIndexBuffer  tib;
    if (bgfx::getAvailTransientVertexBuffer(8, m_layout) < 8) return;
    if (bgfx::getAvailTransientIndexBuffer(20)           < 20) return;
    bgfx::allocTransientVertexBuffer(&tvb, 8,  m_layout);
    bgfx::allocTransientIndexBuffer (&tib, 20);

    bx::memCopy(tvb.data, wverts, sizeof(WorldVertex) * 8);
    bx::memCopy(tib.data, lines,  sizeof(uint16_t) * 20);

    // Identity transform — vertices are already in world space
    float identity[16]; bx::mtxIdentity(identity);
    bgfx::setTransform(identity);
    bgfx::setVertexBuffer(0, &tvb);
    bgfx::setIndexBuffer(&tib);
    bgfx::setState(BGFX_STATE_WRITE_RGB | BGFX_STATE_WRITE_A |
                   BGFX_STATE_PT_LINES  | BGFX_STATE_DEPTH_TEST_LESS);
    bgfx::submit(0, m_program);
}