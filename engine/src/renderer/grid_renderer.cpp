bool GridRenderer::init()
{
    m_layout.begin()
        .add(bgfx::Attrib::Position, 2, bgfx::AttribType::Float)
        .end();

    struct GridVertex { float x, z; };
    static const GridVertex verts[4] = {
        { -1.0f, -1.0f },
        {  1.0f, -1.0f },
        {  1.0f,  1.0f },
        { -1.0f,  1.0f },
    };
    static const uint16_t indices[6] = { 0, 1, 2, 0, 2, 3 };

    m_vbh = bgfx::createVertexBuffer(
        bgfx::makeRef(verts, sizeof(verts)), m_layout);
    m_ibh = bgfx::createIndexBuffer(
        bgfx::makeRef(indices, sizeof(indices)));

    bgfx::ShaderHandle vs = bgfx::createShader(
        bgfx::makeRef(s_vs_grid_dx11, sizeof(s_vs_grid_dx11)));
    bgfx::ShaderHandle fs = bgfx::createShader(
        bgfx::makeRef(s_fs_grid_dx11, sizeof(s_fs_grid_dx11)));

    m_program = bgfx::createProgram(vs, fs, true);

    if (!bgfx::isValid(m_program))
    {
        printf("Grid shader program creation FAILED\n");
        return false;
    }

    printf("Grid renderer initialized\n");
    return true;
}

void GridRenderer::shutdown()
{
    if (bgfx::isValid(m_program)) bgfx::destroy(m_program);
    if (bgfx::isValid(m_vbh))     bgfx::destroy(m_vbh);
    if (bgfx::isValid(m_ibh))     bgfx::destroy(m_ibh);
}

void GridRenderer::draw(const float* viewMtx, const float* projMtx)
{
    const float kGridSize = 1000.0f;
    float model[16];
    bx::mtxScale(model, kGridSize, 1.0f, kGridSize);

    bgfx::setViewTransform(0, viewMtx, projMtx);
    bgfx::setTransform(model);
    bgfx::setVertexBuffer(0, m_vbh);
    bgfx::setIndexBuffer(m_ibh);
    bgfx::setState(
        BGFX_STATE_WRITE_RGB     |
        BGFX_STATE_WRITE_A       |
        BGFX_STATE_DEPTH_TEST_LESS |
        BGFX_STATE_WRITE_Z       |
        BGFX_STATE_BLEND_ALPHA
    );
    bgfx::submit(0, m_program);
}